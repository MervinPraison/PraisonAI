/** Options for {@link ConsoleBackend} (all optional; Python's class takes none). */
export interface ConsoleBackendOptions {
  /** Input stream for the default async reader (default: process.stdin). */
  input?: NodeJS.ReadableStream;
  /** Output stream for prompts (default: process.stdout). */
  output?: NodeJS.WritableStream;
  /** Injected async reader: receives the question, resolves the raw answer. */
  reader?: (question: string) => Promise<string>;
  /** Injected sync reader for `requestApprovalSync`. */
  syncReader?: (question: string) => string;
  /** Force ANSI colours on/off (default: on when the output is a TTY and NO_COLOR is unset). */
  colors?: boolean;
}

/** `(approved, scope, scopePattern, feedback)` as returned by Python's `_prompt_user`. */
export type ConsolePromptResult = [boolean, ApprovalScope, string | null, string | null];

const ANSI = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  red: '\x1b[31m',
  boldRed: '\x1b[1;31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
  white: '\x1b[37m',
} as const;

type AnsiName = keyof typeof ANSI;

const RISK_COLORS: Readonly<Record<string, AnsiName>> = {
  critical: 'boldRed',
  high: 'red',
  medium: 'yellow',
  low: 'blue',
};

function paint(text: string, color: AnsiName, enabled: boolean): string {
  return enabled ? `${ANSI[color]}${text}${ANSI.reset}` : text;
}

type ChoiceOutcome =
  | { kind: 'deny' }
  | { kind: 'redirect' }
  | { kind: 'approve'; scope: ApprovalScope; scopePattern: string | null };

/**
 * Interactive terminal prompt. Default for CLI usage.
 *
 * Python parity: `ConsoleBackend`. Renders the request (function, risk level,
 * agent, diff or arguments) and asks once / this session / always / no /
 * deny-and-redirect. Plain "y"/"yes" is accepted as "once" and "" defaults to
 * "no", matching the Python prompt default.
 *
 * @example
 * ```typescript
 * const backend = new ConsoleBackend({ reader: async () => 'y' });
 * const decision = await backend.requestApproval(approvalRequest({
 *   toolName: 'execute_command', arguments: { command: 'ls' }, riskLevel: 'low',
 * }));
 * decision.approved; // true
 * ```
 */
export class ConsoleBackend implements ApprovalBackend {
  private readonly input: NodeJS.ReadableStream;
  private readonly output: NodeJS.WritableStream;
  private readonly reader?: (question: string) => Promise<string>;
  private readonly syncReader?: (question: string) => string;
  private readonly colors: boolean;

  constructor(options: ConsoleBackendOptions = {}) {
    this.input = options.input ?? process.stdin;
    this.output = options.output ?? process.stdout;
    this.reader = options.reader;
    this.syncReader = options.syncReader;
    const isTTY = Boolean((this.output as { isTTY?: boolean }).isTTY);
    this.colors = options.colors ?? (isTTY && !process.env.NO_COLOR);
  }

  /**
   * Render a unified diff with coloured +/- hunks, bounded to `maxLines`.
   * Python parity: `_render_diff_markup(diff, max_lines=40)` (ANSI instead of Rich markup).
   */
  static renderDiffMarkup(diff: string, maxLines: number = 40, colors: boolean = true): string {
    const lines = diff.split(/\r?\n/);
    const rendered: string[] = [];
    for (let i = 0; i < lines.length; i++) {
      if (i >= maxLines) {
        rendered.push(paint('... (diff truncated)', 'dim', colors));
        break;
      }
      const line = lines[i];
      if (line.startsWith('+++') || line.startsWith('---')) rendered.push(paint(line, 'bold', colors));
      else if (line.startsWith('@@')) rendered.push(paint(line, 'cyan', colors));
      else if (line.startsWith('+')) rendered.push(paint(line, 'green', colors));
      else if (line.startsWith('-')) rendered.push(paint(line, 'red', colors));
      else rendered.push(paint(line, 'dim', colors));
    }
    return rendered.join('\n') + '\n';
  }

  /** Build the panel text and the choice question for `request`. */
  private buildPrompt(request: ApprovalBackendRequest): { panel: string; question: string; suggested: string } {
    const riskLevel = String(request.riskLevel ?? 'unknown');
    const riskColor: AnsiName = RISK_COLORS[riskLevel] ?? 'white';
    const c = this.colors;

    let toolInfo = `${paint('Function:', 'bold', c)} ${request.toolName}\n`;
    toolInfo += `${paint('Risk Level:', 'bold', c)} ${paint(riskLevel.toUpperCase(), riskColor, c)}\n`;
    if (request.agentName) {
      toolInfo += `${paint('Agent:', 'bold', c)} ${request.agentName}\n`;
    }

    const diff = request.context?.diff;
    if (typeof diff === 'string' && diff) {
      toolInfo += `${paint('Diff:', 'bold', c)}\n`;
      toolInfo += ConsoleBackend.renderDiffMarkup(diff, 40, c);
    } else {
      toolInfo += `${paint('Arguments:', 'bold', c)}\n`;
      for (const [key, value] of Object.entries(request.arguments ?? {})) {
        let strValue = typeof value === 'string' ? value : JSON.stringify(value);
        if (strValue === undefined) strValue = String(value);
        if (strValue.length > 100) strValue = strValue.slice(0, 97) + '...';
        toolInfo += `  ${key}: ${strValue}\n`;
      }
    }

    const rule = paint('─'.repeat(60), riskColor, c);
    const panel =
      `\n${rule}\n${paint('🔒 Tool Approval Required', 'bold', c)}\n${rule}\n` + `${toolInfo.trimEnd()}\n${rule}\n`;

    const suggested = suggestScopePattern(request);
    const alwaysLabel = suggested ? `always (${suggested})` : 'always';
    const question =
      `${paint(`Allow ${request.toolName}?`, riskColor, c)}  ` +
      `[o] once   [s] this session   [a] ${alwaysLabel}   [n] no   [d] deny & redirect\n` +
      `Choice [o/s/a/n/d] (n): `;
    return { panel, question, suggested };
  }

  /** Map a raw answer to an outcome; unknown answers fall back to the "n" default. */
  private interpret(answer: string, suggested: string): ChoiceOutcome {
    const choice = (answer ?? '').trim().toLowerCase();
    switch (choice) {
      case 'o':
      case 'once':
      case 'y':
      case 'yes':
        return { kind: 'approve', scope: 'once', scopePattern: null };
      case 's':
      case 'session':
        return { kind: 'approve', scope: 'session', scopePattern: null };
      case 'a':
      case 'always':
        return { kind: 'approve', scope: 'always', scopePattern: suggested || null };
      case 'd':
      case 'deny':
      case 'redirect':
        return { kind: 'redirect' };
      default:
        return { kind: 'deny' };
    }
  }

  private write(text: string): void {
    this.output.write(text);
  }

  /** Ask one question with the injected reader or a readline interface. */
  private async ask(question: string): Promise<string> {
    if (this.reader) return this.reader(question);
    const readline = await import('readline');
    const rl = readline.createInterface({ input: this.input, output: this.output });
    return new Promise<string>((resolve, reject) => {
      let settled = false;
      rl.once('close', () => {
        // `rl.close()` fires this synchronously; only a genuine EOF (close
        // before any answer) should reject.
        if (!settled) reject(new Error('EOF'));
      });
      rl.question(question, (answer) => {
        settled = true;
        resolve(answer);
        rl.close();
      });
    });
  }

  /** Ask one question synchronously with the injected reader or a blocking stdin read. */
  private askSync(question: string): string {
    if (this.syncReader) return this.syncReader(question);
    if (this.input !== process.stdin) {
      throw new Error('ConsoleBackend.requestApprovalSync needs a syncReader when input is not process.stdin');
    }
    this.write(question);
    const buf = Buffer.alloc(1);
    let line = '';
    for (;;) {
      let n: number;
      try {
        n = fs.readSync(0, buf, 0, 1, null);
      } catch (err) {
        if ((err as NodeJS.ErrnoException).code === 'EAGAIN') continue;
        throw err;
      }
      if (n === 0) {
        if (!line) throw new Error('EOF');
        break;
      }
      const ch = buf.toString('utf8');
      if (ch === '\n') break;
      line += ch;
    }
    return line.replace(/\r$/, '');
  }

  /**
   * Show the panel and ask once/session/always/no/deny-with-guidance.
   * Python parity: `_prompt_user(request)`; resolves
   * `[approved, scope, scopePattern, feedback]`.
   */
  async promptUser(request: ApprovalBackendRequest): Promise<ConsolePromptResult> {
    const { panel, question, suggested } = this.buildPrompt(request);
    this.write(panel);

    let answer: string;
    try {
      answer = await this.ask(question);
    } catch {
      return [false, 'once', null, null];
    }
    const outcome = this.interpret(answer, suggested);
    if (outcome.kind === 'deny') return [false, 'once', null, null];
    if (outcome.kind === 'redirect') {
      let feedback = '';
      try {
        feedback = (await this.ask('What should the agent do instead? ')).trim();
      } catch {
        feedback = '';
      }
      return [false, 'once', null, feedback || null];
    }
    return [true, outcome.scope, outcome.scopePattern, null];
  }

  /** Synchronous twin of {@link promptUser}. */
  promptUserSync(request: ApprovalBackendRequest): ConsolePromptResult {
    const { panel, question, suggested } = this.buildPrompt(request);
    this.write(panel);

    let answer: string;
    try {
      answer = this.askSync(question);
    } catch {
      return [false, 'once', null, null];
    }
    const outcome = this.interpret(answer, suggested);
    if (outcome.kind === 'deny') return [false, 'once', null, null];
    if (outcome.kind === 'redirect') {
      let feedback = '';
      try {
        feedback = this.askSync('What should the agent do instead? ').trim();
      } catch {
        feedback = '';
      }
      return [false, 'once', null, feedback || null];
    }
    return [true, outcome.scope, outcome.scopePattern, null];
  }

  private static toDecision([approved, scope, scopePattern, feedback]: ConsolePromptResult): ApprovalBackendDecision {
    if (approved) {
      return approvalDecision({
        approved: true,
        reason: `User approved (${scope})`,
        approver: 'console',
        scope,
        scopePattern,
      });
    }
    return approvalDecision({
      approved: false,
      reason: feedback ? `User denied: ${feedback}` : 'User denied',
      approver: 'console',
      feedback,
    });
  }

  /** Synchronous approval via the console prompt. */
  requestApprovalSync(request: ApprovalBackendRequest): ApprovalBackendDecision {
    try {
      return ConsoleBackend.toDecision(this.promptUserSync(request));
    } catch (e) {
      void Logger.error(`Console approval error: ${(e as Error).message ?? e}`);
      return approvalDecision({ approved: false, reason: `Approval error: ${(e as Error).message ?? e}` });
    }
  }

  /** Async approval via the console prompt. */
  async requestApproval(request: ApprovalBackendRequest): Promise<ApprovalBackendDecision> {
    try {
      return ConsoleBackend.toDecision(await this.promptUser(request));
    } catch (e) {
      void Logger.error(`Console approval error: ${(e as Error).message ?? e}`);
      return approvalDecision({ approved: false, reason: `Approval error: ${(e as Error).message ?? e}` });
    }
  }
}

