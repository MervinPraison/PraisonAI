/** Options for {@link approvalHandlerFromBackend} / {@link setApprovalBackend}. */
export interface BackendHandlerOptions {
  /** Risk level stamped on requests coming from `ApprovalManager` (it carries none). Default "medium". */
  riskLevel?: string;
  /** Agent name stamped on requests. */
  agentName?: string | null;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Convert an `ApprovalManager` request into the Python-shaped backend request. */
export function toApprovalBackendRequest(
  request: ToolApprovalRequest,
  options: BackendHandlerOptions = {},
): ApprovalBackendRequest {
  const { riskLevel = 'medium', agentName = null } = options;
  return approvalRequest({
    toolName: request.toolName,
    arguments: isPlainObject(request.input) ? request.input : { input: request.input },
    riskLevel,
    agentName,
    context: {
      requestId: request.requestId,
      toolInvocationId: request.toolInvocationId,
      reason: request.reason,
      timestamp: request.timestamp,
    },
  });
}

/** Adapt an {@link ApprovalBackend} into an `ApprovalManager` handler. */
export function approvalHandlerFromBackend(backend: ApprovalBackend, options: BackendHandlerOptions = {}): ApprovalHandler {
  return async (request: ToolApprovalRequest): Promise<boolean> => {
    const decision = await backend.requestApproval(toApprovalBackendRequest(request, options));
    return decision.approved;
  };
}

interface BackendSlot {
  backend: ApprovalBackend | null;
  options: BackendHandlerOptions;
}

const backendSlots = new WeakMap<ApprovalManager, BackendSlot>();

/**
 * Install `backend` as the approval backend of `manager` (default: the global
 * `ApprovalManager`). A single delegating handler is registered per manager
 * the first time; later calls swap the backend behind it. Passing `null`
 * detaches the backend (the handler then declines, so the manager's other
 * handlers or its event flow decide).
 *
 * @example
 * ```typescript
 * setApprovalBackend(new AutoApproveBackend());
 * await getApprovalManager().requestApproval({ toolName: 'rm', input: {} }); // true
 * ```
 */
export function setApprovalBackend(
  backend: ApprovalBackend | null,
  manager: ApprovalManager = getApprovalManager(),
  options: BackendHandlerOptions = {},
): void {
  let slot = backendSlots.get(manager);
  if (!slot) {
    slot = { backend, options };
    backendSlots.set(manager, slot);
    const current = slot;
    manager.onApprovalRequest(async (request: ToolApprovalRequest) => {
      if (!current.backend) return false;
      const decision = await current.backend.requestApproval(toApprovalBackendRequest(request, current.options));
      return decision.approved;
    });
    return;
  }
  slot.backend = backend;
  slot.options = options;
}

/** The approval backend installed on `manager` (default: the global one), or null. */
export function getApprovalBackend(manager: ApprovalManager = getApprovalManager()): ApprovalBackend | null {
  return backendSlots.get(manager)?.backend ?? null;
}
