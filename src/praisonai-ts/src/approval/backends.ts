/** Duck-typed approver: anything with `achat` or `chat`. */
export interface ApproverAgentLike {
  name?: string;
  achat?: (prompt: string) => Promise<unknown>;
  chat?: (prompt: string) => unknown | Promise<unknown>;
}

/**
 * Delegates approval decisions to another AI agent.
 *
 * Python parity: `AgentApproval(approver_agent=None, llm="gpt-4o-mini")`. The
 * approver receives a structured prompt and answers APPROVE or DENY. Without
 * an approver a default reviewer `Agent` is created lazily.
 *
 * `requestApprovalSync` cannot block on the event loop in JavaScript; it
 * returns a denial whose reason says to use `requestApproval` (Python's
 * error path also resolves to a denial with a reason).
 */
export class AgentApproval implements ApprovalBackend {
  private approverAgent: ApproverAgentLike | null;
  private readonly llm: string;

  constructor(approverAgent: ApproverAgentLike | null = null, llm: string = 'gpt-4o-mini') {
    this.approverAgent = approverAgent;
    this.llm = llm;
  }

  toString(): string {
    const name = this.approverAgent?.name || 'default';
    return `AgentApproval(approver=${JSON.stringify(name)})`;
  }

  /** Lazily create or return the approver agent. Python parity: `_get_approver`. */
  protected async getApprover(): Promise<ApproverAgentLike> {
    if (this.approverAgent !== null) return this.approverAgent;
    const { Agent } = await import('../agent/simple');
    this.approverAgent = new Agent({
      name: 'approval-reviewer',
      instructions:
        'You are a security reviewer for tool execution requests. ' +
        'Evaluate each request and respond with exactly one word: ' +
        'APPROVE or DENY. Consider the tool name, arguments, and risk level. ' +
        'Deny anything that looks destructive, dangerous, or unauthorized. ' +
        'Approve safe read-only operations.',
      llm: this.llm,
    }) as unknown as ApproverAgentLike;
    return this.approverAgent;
  }

  /** Build the evaluation prompt for the approver agent. Python parity: `_build_prompt`. */
  protected buildPrompt(request: ApprovalBackendRequest): string {
    const entries = Object.entries(request.arguments ?? {});
    const argsStr = entries.length
      ? entries.map(([k, v]) => `  ${k}: ${typeof v === 'string' ? v : JSON.stringify(v)}`).join('\n')
      : '  (none)';
    return (
      'Tool Approval Request:\n' +
      `  Tool: ${request.toolName}\n` +
      `  Risk Level: ${String(request.riskLevel).toUpperCase()}\n` +
      `  Agent: ${request.agentName || 'unknown'}\n` +
      `  Arguments:\n${argsStr}\n\n` +
      'Respond with exactly one word: APPROVE or DENY'
    );
  }

  /** Ask the approver agent to evaluate the request. */
  async requestApproval(request: ApprovalBackendRequest): Promise<ApprovalBackendDecision> {
    try {
      const approver = await this.getApprover();
      const prompt = this.buildPrompt(request);

      let response: unknown;
      if (typeof approver.achat === 'function') {
        response = await approver.achat(prompt);
      } else if (typeof approver.chat === 'function') {
        response = await approver.chat(prompt);
      } else {
        return approvalDecision({ approved: false, reason: 'Approver agent has no chat method' });
      }

      const text = String(response).trim();
      const upper = text.toUpperCase();
      const approved = upper.includes('APPROVE') && !upper.includes('DENY');
      return approvalDecision({
        approved,
        reason: `Agent ${approved ? 'approved' : 'denied'}: ${text.slice(0, 200)}`,
        approver: approver.name ?? 'agent',
        metadata: { platform: 'agent', response: text.slice(0, 500) },
      });
    } catch (e) {
      void Logger.error(`AgentApproval error: ${(e as Error).message ?? e}`);
      return approvalDecision({ approved: false, reason: `Agent approval error: ${(e as Error).message ?? e}` });
    }
  }

  /** Not supported synchronously in JavaScript; resolves to a denial explaining why. */
  requestApprovalSync(request: ApprovalBackendRequest): ApprovalBackendDecision {
    void request;
    return approvalDecision({
      approved: false,
      reason: 'Agent approval error: requestApprovalSync cannot block on the event loop; use requestApproval()',
    });
  }
}

// ============================================================================
// CallbackBackend
// ============================================================================

/** Legacy `(functionName, arguments, riskLevel)` approval callback. */
export type LegacyApprovalCallback = (
  functionName: string,
  args: Record<string, unknown>,
  riskLevel: string,
) => ApprovalBackendDecision | boolean | unknown | Promise<ApprovalBackendDecision | boolean | unknown>;

function isDecision(value: unknown): value is ApprovalBackendDecision {
  return typeof value === 'object' && value !== null && typeof (value as ApprovalBackendDecision).approved === 'boolean'
    && 'reason' in (value as object);
}

/** Object carrying an explicit boolean `approved` field (may omit `reason`). */
function hasApprovedField(value: unknown): value is Partial<ApprovalBackendDecision> & { approved: boolean } {
  return typeof value === 'object' && value !== null
    && typeof (value as { approved?: unknown }).approved === 'boolean';
}

function coerceDecision(result: unknown): ApprovalBackendDecision {
  if (isDecision(result)) return result;
  // A partial decision such as `{ approved: false }` must stay a denial:
  // normalise it through approvalDecision rather than falling through to the
  // truthiness path below (a non-empty object is truthy, which would flip it).
  if (hasApprovedField(result)) return approvalDecision({ ...result });
  if (typeof result === 'boolean') return approvalDecision({ approved: result });
  return approvalDecision({ approved: Boolean(result) });
}

/**
 * Wraps a legacy `(functionName, arguments, riskLevel)` callback into an
 * {@link ApprovalBackend}. Python parity: `CallbackBackend(callback)`.
 */
export class CallbackBackend implements ApprovalBackend {
  private readonly callback: LegacyApprovalCallback;

  constructor(callback: LegacyApprovalCallback) {
    this.callback = callback;
  }

  requestApprovalSync(request: ApprovalBackendRequest): ApprovalBackendDecision {
    const result = this.callback(request.toolName, request.arguments, request.riskLevel);
    if (result instanceof Promise) {
      throw new Error('CallbackBackend.requestApprovalSync received a Promise; use requestApproval()');
    }
    return coerceDecision(result);
  }

  async requestApproval(request: ApprovalBackendRequest): Promise<ApprovalBackendDecision> {
    const result = await this.callback(request.toolName, request.arguments, request.riskLevel);
    return coerceDecision(result);
  }
}

