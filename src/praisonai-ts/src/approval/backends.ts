/** Tool names that map to a shell-command permission target (`bash:<command>`). */
const SHELL_TOOLS: ReadonlySet<string> = new Set(['execute_command', 'acp_execute_command']);

/** File-mutating tool names -> permission-target prefix for their path. */
const FILE_TOOL_PREFIXES: Readonly<Record<string, string>> = {
  edit_file: 'edit',
  acp_edit_file: 'edit',
  write_file: 'write',
  acp_create_file: 'write',
  delete_file: 'delete',
  acp_delete_file: 'delete',
  move_file: 'move',
  copy_file: 'copy',
};

const COMMAND_KEYS = ['command', 'cmd', 'code', 'query'];
const PATH_KEYS = ['file_path', 'path', 'filename', 'file', 'target', 'filepath', 'src'];

/**
 * Build a permission-store target for a tool call.
 * Python parity: `build_permission_target(tool_name, arguments=None)`.
 * Shell tools -> `bash:<command>`, file tools -> `<edit|write|...>:<path>`,
 * everything else -> `tool:<tool_name>`.
 */
export function buildPermissionTarget(toolName: string, args: Record<string, unknown> | null = null): string {
  const a = args ?? {};
  const firstString = (keys: string[]): string | null => {
    for (const key of keys) {
      const value = a[key];
      if (typeof value === 'string' && value.trim()) return value.trim();
    }
    return null;
  };

  if (SHELL_TOOLS.has(toolName)) {
    const command = firstString(COMMAND_KEYS);
    return command ? `bash:${command}` : `tool:${toolName}`;
  }

  const prefix = FILE_TOOL_PREFIXES[toolName];
  if (prefix !== undefined) {
    const path = firstString(PATH_KEYS);
    return path ? `${prefix}:${path}` : `tool:${toolName}`;
  }

  return `tool:${toolName}`;
}

/**
 * Command -> number of leading tokens to keep as the reusable prefix.
 * Python parity: `ARITY` in permissions/arity.py.
 */
export const ARITY: Readonly<Record<string, number>> = Object.freeze({
  git: 2,
  gh: 2,
  hg: 2,
  svn: 2,
  npm: 2,
  yarn: 2,
  pnpm: 2,
  pip: 2,
  cargo: 2,
  go: 2,
  poetry: 2,
  uv: 2,
  make: 2,
  docker: 2,
  'docker compose': 2,
  kubectl: 2,
  helm: 2,
  python: 2,
  python3: 2,
  pytest: 1,
  ruff: 2,
  apt: 2,
  'apt-get': 2,
  brew: 2,
  systemctl: 2,
});

/** Return the longest meaningful command prefix for `tokens`. Python parity: `prefix(tokens, arity_map=None)`. */
export function commandPrefix(tokens: string[], arityMap: Record<string, number> | null = null): string {
  if (tokens.length === 0) return '';
  const table = arityMap ?? ARITY;
  const keyWordCounts = [...new Set(Object.keys(table).map((k) => k.split(/\s+/).length))].sort((x, y) => y - x);
  for (const n of keyWordCounts) {
    if (n > tokens.length) continue;
    const candidate = tokens.slice(0, n).join(' ');
    if (candidate in table) {
      const keep = Math.min(table[candidate], tokens.length);
      return tokens.slice(0, keep).join(' ');
    }
  }
  return tokens[0];
}

const SHELL_OPERATORS = ['&&', '||', '|', ';', '&', '$(', '`', '>', '<', '\n'];

/**
 * Derive a reusable glob pattern for a shell approval target.
 * Python parity: `derive_pattern(target, arity_map=None)`. Only `bash:`/`shell:`
 * targets are generalised; a bare single-token command, an existing glob, or a
 * command containing a shell operator is returned unchanged.
 *
 * @example derivePattern('bash:git status -s') === 'bash:git status *'
 */
export function derivePattern(target: string, arityMap: Record<string, number> | null = null): string {
  const matched = ['bash:', 'shell:'].find((p) => target.startsWith(p));
  if (matched === undefined) return target;

  const command = target.slice(matched.length).trim();
  if (!command) return target;
  if (command.includes('*') || command.includes('?')) return target;
  if (SHELL_OPERATORS.some((op) => command.includes(op))) return target;

  const tokens = command.split(/\s+/);
  const cmdPrefix = commandPrefix(tokens, arityMap);
  if (!cmdPrefix) return target;
  if (cmdPrefix.split(' ').length === 1 && cmdPrefix === command) return target;

  return `${matched}${cmdPrefix} *`;
}

/** Return a reusable "always" pattern for `request` (best-effort). Python parity: `_suggest_scope_pattern`. */
export function suggestScopePattern(request: ApprovalBackendRequest): string {
  const target = buildPermissionTarget(request.toolName, request.arguments);
  try {
    return derivePattern(target);
  } catch {
    return target;
  }
}

