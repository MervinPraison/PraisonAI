/** How long an approval decision should be remembered. */
export type ApprovalScope = 'once' | 'session' | 'always';

/**
 * Request for tool-execution approval.
 * Python parity: `ApprovalRequest` (dataclass) in approval/protocols.py.
 */
export interface ApprovalBackendRequest {
  /** Name of the tool requesting approval. */
  toolName: string;
  /** Arguments the tool will be called with. */
  arguments: Record<string, unknown>;
  /** Risk classification (critical / high / medium / low). */
  riskLevel: string;
  /** Name of the agent that triggered the call. */
  agentName?: string | null;
  /** Session identifier for tracking. */
  sessionId?: string | null;
  /** Arbitrary context for backend-specific data (e.g. a rendered `diff`). */
  context?: Record<string, unknown>;
  /** Stable correlation id; auto-generated by {@link approvalRequest}. */
  approvalId?: string;
  /** Reviewer identities allowed to resolve this request (null = anyone). */
  authorizedReviewers?: string[] | null;
  /** Zero-arg predicate returning true while the originating turn is still live. */
  liveness?: (() => boolean) | null;
}

/**
 * Result of an approval request.
 * Python parity: `ApprovalDecision` (dataclass) in approval/protocols.py.
 */
export interface ApprovalBackendDecision {
  approved: boolean;
  reason: string;
  /** Optional replacement arguments (empty = use originals). */
  modifiedArgs: Record<string, unknown>;
  /** Who/what approved (user, system, console, agent, ...). */
  approver: string | null;
  metadata: Record<string, unknown>;
  scope: ApprovalScope;
  /** Reusable target/pattern to persist for session/always scopes. */
  scopePattern: string | null;
  /** Free-text guidance supplied when denying ("deny with guidance"). */
  feedback: string | null;
}

/** Fields accepted by {@link approvalRequest}. */
export interface ApprovalRequestInit {
  toolName: string;
  arguments: Record<string, unknown>;
  riskLevel: string;
  agentName?: string | null;
  sessionId?: string | null;
  context?: Record<string, unknown>;
  approvalId?: string;
  authorizedReviewers?: string[] | null;
  liveness?: (() => boolean) | null;
}

/**
 * Build an {@link ApprovalBackendRequest} with the Python dataclass defaults
 * (`approvalId` is generated like Python's `uuid4().hex`).
 */
export function approvalRequest(init: ApprovalRequestInit): Required<ApprovalBackendRequest> {
  const {
    toolName,
    arguments: args,
    riskLevel,
    agentName = null,
    sessionId = null,
    context = {},
    approvalId = randomUUID().replace(/-/g, ''),
    authorizedReviewers = null,
    liveness = null,
  } = init;
  return { toolName, arguments: args, riskLevel, agentName, sessionId, context, approvalId, authorizedReviewers, liveness };
}

/** Fields accepted by {@link approvalDecision}; only `approved` is required. */
export interface ApprovalDecisionInit {
  approved: boolean;
  reason?: string;
  modifiedArgs?: Record<string, unknown>;
  approver?: string | null;
  metadata?: Record<string, unknown>;
  scope?: ApprovalScope;
  scopePattern?: string | null;
  feedback?: string | null;
}

/** Build an {@link ApprovalBackendDecision} with the Python dataclass defaults. */
export function approvalDecision(init: ApprovalDecisionInit): ApprovalBackendDecision {
  const {
    approved,
    reason = '',
    modifiedArgs = {},
    approver = null,
    metadata = {},
    scope = 'once',
    scopePattern = null,
    feedback = null,
  } = init;
  return { approved, reason, modifiedArgs, approver, metadata, scope, scopePattern, feedback };
}

