"""X-19: every environment variable the core SDK reads is listed in docs/env-vars.md.

The table has only the name and its kind, not where it is read, so moving a
file or reading a variable in one more place does not change it.

The table is generated from the source by an AST scan, so a new variable read
fails this test until the table is regenerated:

    python tests/unit/test_env_var_reference.py --write

What counts as a read: ``os.environ.get/setdefault/pop("X")``, ``os.environ["X"]``,
``"X" in os.environ``, ``os.getenv("X")`` and any call whose function name
contains ``env`` with an upper-case string first argument (``_env_bool("X")``).
A module-level constant (``ENV_VAR = "PRAISONAI_HOME"``) used as the key is
resolved. Names built at run time (f-strings) cannot be listed.
"""

import ast
import re
import sys
from pathlib import Path

PKG_ROOT = Path(__file__).resolve().parents[2]
SOURCE = PKG_ROOT / "praisonaiagents"
TABLE = PKG_ROOT / "docs" / "env-vars.md"

_NAME = re.compile(r"^[A-Z][A-Z0-9_]{2,}$")
_SECURITY = re.compile(r"ALLOW|TRUST|APPROV|SAFETY|UNSAFE|INSECURE|STRICT|ENFORCE|ORIGINS")
_CREDENTIAL = re.compile(r"API_KEY|TOKEN|PASSWORD|SECRET|CONNECTION_STRING")


def _is_environ(node):
    if isinstance(node, ast.Attribute):
        return node.attr == "environ" and isinstance(node.value, ast.Name) and node.value.id == "os"
    return isinstance(node, ast.Name) and node.id == "environ"


def _key(node):
    if isinstance(node, ast.Call):
        f = node.func
        if isinstance(f, ast.Attribute) and f.attr in ("get", "setdefault", "pop") and _is_environ(f.value):
            return node.args[0] if node.args else None
        name = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
        if "env" in name.lower() and node.args:
            return node.args[0]
    elif isinstance(node, ast.Subscript) and _is_environ(node.value):
        return node.slice
    elif (isinstance(node, ast.Compare) and len(node.ops) == 1
          and isinstance(node.ops[0], (ast.In, ast.NotIn)) and _is_environ(node.comparators[0])):
        return node.left
    return None


def scan():
    """Sorted names of the variables read in the package."""
    found = set()
    for path in sorted(SOURCE.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        consts = {
            t.id: n.value.value
            for n in tree.body if isinstance(n, ast.Assign) and isinstance(n.value, ast.Constant)
            for t in n.targets if isinstance(t, ast.Name) and isinstance(n.value.value, str)
        }
        for node in ast.walk(tree):
            key = _key(node)
            if isinstance(key, ast.Name):
                key = ast.Constant(consts.get(key.id))
            if isinstance(key, ast.Constant) and isinstance(key.value, str) and _NAME.match(key.value):
                found.add(key.value)
    return sorted(found)


def _kind(name):
    if _SECURITY.search(name):
        return "security switch"
    if _CREDENTIAL.search(name):
        return "credential"
    return ""


def render(found):
    own = sum(k.startswith(("PRAISONAI_", "PRAISON_")) for k in found)
    lines = [
        "# Environment variables read by praisonaiagents",
        "",
        "<!-- Generated by tests/unit/test_env_var_reference.py --write; do not edit by hand. -->",
        "",
        f"{len(found)} variables, {own} of them `PRAISONAI_*`/`PRAISON_*`. "
        "\"Security switch\" marks a variable that loosens or tightens a safety check; "
        "\"credential\" marks a secret. Names built at run time are not listed.",
        "",
        "| Variable | Kind |",
        "|---|---|",
    ]
    for name in found:
        lines.append(f"| `{name}` | {_kind(name)} |")
    return "\n".join(lines) + "\n"


def test_env_var_reference_is_current():
    expected = render(scan())
    actual = TABLE.read_text(encoding="utf-8") if TABLE.exists() else ""
    assert actual == expected, (
        "docs/env-vars.md is out of date. Regenerate it with: "
        "python tests/unit/test_env_var_reference.py --write"
    )


def test_scan_sees_constant_and_helper_reads():
    found = scan()
    assert "PRAISONAI_HOME" in found  # read through paths.ENV_VAR
    assert "PRAISONAI_PRE_COMPACTION_FLUSH" in found  # read through _env_bool()
    assert _kind("PRAISONAI_AUTO_APPROVE") == "security switch"


if __name__ == "__main__" and "--write" in sys.argv:
    TABLE.write_text(render(scan()), encoding="utf-8")
    print(f"wrote {TABLE}")
